            unset($item['variants']);

            $product = Accessory::query()->updateOrCreate(
                ['slug' => Str::slug($item['name'])],
                [
                    'name' => $item['name'],
                    'type' => $item['type'],
                    'category' => $item['category'],
                    'excerpt' => $item['excerpt'],
                    'description' => $item['description'],
                    'price' => $item['price'],
                    'compare_at_price' => $item['compare_at_price'],
                    'stock' => $item['stock'],
                    'is_featured' => $item['is_featured'],
                    'sort_order' => $item['sort_order'],
                    'is_active' => true,
                ]
            );

            if ($variants === []) {
                continue;
            }

            AccessoryVariant::query()->where('accessory_id', $product->id)->delete();

            foreach ($variants as $index => $variant) {
                AccessoryVariant::query()->create([
                    'accessory_id' => $product->id,
                    'storage' => $variant['storage'] ?? null,
                    'color' => $variant['color'] ?? null,
                    'condition' => $variant['condition'] ?? null,
                    'unlock_status' => $variant['unlock_status'] ?? null,
                    'ram' => $variant['ram'] ?? null,
                    'cpu' => $variant['cpu'] ?? null,
                    'screen_size' => $variant['screen_size'] ?? null,
                    'price' => $variant['price'],
                    'compare_at_price' => $variant['compare_at_price'] ?? null,
                    'stock' => $variant['stock'] ?? null,
                    'sort_order' => $index + 1,
                    'is_active' => true,
                ]);
            }
        }
    }
